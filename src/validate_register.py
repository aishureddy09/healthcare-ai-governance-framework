"""Validate the healthcare-AI risk register and generate assurance outputs.

Usage:  python -m src.validate_register [--register PATH] [--outdir PATH]

The tool checks structural completeness and traceability only. A complete
register is not evidence that a system is safe or legally compliant — it is
evidence that the questions were asked and assigned. This is a desk-research
framework, not a validated standard and not legal advice.
"""
import argparse
import csv
import sys
from pathlib import Path

REQUIRED = ["risk_id", "lifecycle_stage", "risk", "harm", "affected_group",
            "likelihood", "severity", "likelihood_severity_rationale",
            "evidence_needed", "owner", "mitigation", "monitoring_indicator"]
STAGES = ["Data collection", "Annotation", "Development", "Validation",
          "Procurement", "Deployment", "Monitoring", "Privacy and security",
          "Accountability", "Retirement"]
ROOT = Path(__file__).resolve().parents[1]


def load_register(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def validate(rows):
    """Return (errors, warnings, stats). Errors = structural failures."""
    errors, warnings = [], []
    if not rows:
        return ["register is empty"], [], {}
    missing_cols = [c for c in REQUIRED if c not in rows[0]]
    if missing_cols:
        errors.append(f"missing columns: {missing_cols}")
        return errors, warnings, {}
    seen, filled = set(), 0
    for i, r in enumerate(rows, start=2):
        rid = (r.get("risk_id") or "").strip()
        if not rid:
            errors.append(f"row {i}: empty risk_id")
        elif rid in seen:
            errors.append(f"row {i}: duplicate risk_id {rid}")
        seen.add(rid)
        for c in REQUIRED:
            if (r.get(c) or "").strip():
                filled += 1
            else:
                errors.append(f"row {i} ({rid or '?'}): empty field '{c}'")
        for c in ("likelihood", "severity"):
            try:
                v = int(r[c])
                if not 1 <= v <= 5:
                    errors.append(f"row {i} ({rid}): {c}={v} outside 1-5")
            except (TypeError, ValueError):
                errors.append(f"row {i} ({rid}): {c} not an integer")
        if r["lifecycle_stage"] not in STAGES:
            warnings.append(f"row {i} ({rid}): non-standard stage '{r['lifecycle_stage']}'")
    total_cells = len(rows) * len(REQUIRED)
    stages_present = sorted({r["lifecycle_stage"] for r in rows})
    high = [r["risk_id"] for r in rows
            if r.get("likelihood", "").isdigit() and r.get("severity", "").isdigit()
            and int(r["likelihood"]) * int(r["severity"]) >= 15]
    stats = {"n_risks": len(rows), "completeness_pct": round(100 * filled / total_cells, 1),
             "traceability_pct": round(100 * filled / total_cells, 1),
             "stages_covered": stages_present,
             "stages_missing": [s for s in STAGES if s not in stages_present],
             "high_priority_risks": high}
    return errors, warnings, stats


def risk_score(row):
    return int(row["likelihood"]) * int(row["severity"])


def render_assurance_report(rows, stats, errors, warnings):
    lines = ["# Assurance report — AI-assisted skin-lesion triage (case study)",
             "",
             "> Generated by `src/validate_register.py` from `risk_register.csv`.",
             "> Desk-research framework only: not a validated standard, not legal "
             "advice, and not a certification of regulatory compliance.",
             "",
             f"- Risks registered: **{stats['n_risks']}**",
             f"- Field completeness / traceability: **{stats['completeness_pct']}%** "
             "(every risk should carry an owner, evidence requirement, mitigation "
             "and monitoring indicator)",
             f"- Lifecycle stages covered: {', '.join(stats['stages_covered'])}",
             f"- Stages missing: {', '.join(stats['stages_missing']) or 'none'}",
             f"- Validation errors: {len(errors)}; warnings: {len(warnings)}",
             "",
             "## Highest-priority risks (likelihood x severity >= 15)",
             "",
             "| ID | Stage | Risk | Score | Owner | Monitoring indicator |",
             "|---|---|---|---|---|---|"]
    for r in sorted(rows, key=risk_score, reverse=True):
        if risk_score(r) >= 15:
            lines.append(f"| {r['risk_id']} | {r['lifecycle_stage']} | {r['risk']} | "
                         f"{risk_score(r)} | {r['owner']} | {r['monitoring_indicator']} |")
    lines += ["", "## Pre-deployment evidence gate", "",
              "Go-live should be blocked until each high-priority risk has its "
              "`evidence_needed` item on file: external validation (R06), per-class "
              "and subgroup sensitivity with intervals (R04, R07), a signed "
              "responsibility matrix (R17), and an intended-use statement limiting "
              "the tool to prioritisation support (R10).", "",
              "## Errors and warnings", ""]
    lines += [f"- ERROR: {e}" for e in errors] or ["- No errors."]
    lines += [f"- Warning: {w}" for w in warnings]
    return "\n".join(lines) + "\n"


def render_policy_brief(rows, stats):
    top = sorted(rows, key=risk_score, reverse=True)[:3]
    lines = ["# Policy brief: governing AI-assisted skin-lesion triage",
             "",
             "**Status:** two-page-style brief from a student desk-research "
             "framework. Not legal advice; not a validated standard.",
             "",
             "## The decision", "",
             "A skin-lesion AI that *prioritises images for clinician review* can "
             "shorten waits — but only if the evidence, oversight and accountability "
             "around it are settled before the first patient is triaged by it. The "
             "system must never be framed as making the diagnosis.",
             "",
             "## What the risk register shows", "",
             f"This framework tracks {stats['n_risks']} risks across "
             f"{len(stats['stages_covered'])} lifecycle stages, at "
             f"{stats['completeness_pct']}% field completeness. The three "
             "highest-scoring risks are:", ""]
    for r in top:
        lines.append(f"- **{r['risk_id']} — {r['risk']}** (score {risk_score(r)}/25). "
                     f"Harm: {r['harm']}. Mitigation: {r['mitigation']}.")
    lines += ["", "## Three recommendations", "",
              "1. **Evidence before deployment.** Require external validation and "
              "per-class, subgroup-reported sensitivity with uncertainty intervals "
              "before go-live at any site — headline accuracy is not assurance.",
              "2. **Humans visibly in charge.** Record the clinician's own judgement "
              "before revealing model output for high-risk cases, label the tool as "
              "prioritisation support only, and audit override rates.",
              "3. **Monitor or withdraw.** Fund rolling drift and false-negative "
              "audits with pre-agreed triggers; a system nobody monitors should not "
              "stay live.", "",
              "## What this brief is not", "",
              "It does not certify compliance with any law or standard. Decision-makers "
              "must check current official guidance and take qualified advice for "
              "their own deployment.", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--register", default=str(ROOT / "risk_register.csv"))
    ap.add_argument("--outdir", default=str(ROOT / "reports"))
    a = ap.parse_args(argv)
    rows = load_register(a.register)
    errors, warnings, stats = validate(rows)
    out = Path(a.outdir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "assurance_report.md").write_text(render_assurance_report(rows, stats, errors, warnings))
    (out / "policy_brief.md").write_text(render_policy_brief(rows, stats))
    print(f"Risks: {stats.get('n_risks')} | completeness: {stats.get('completeness_pct')}% "
          f"| stages covered: {len(stats.get('stages_covered', []))}/{len(STAGES)} "
          f"| high-priority: {stats.get('high_priority_risks')}")
    for e in errors:
        print("ERROR:", e)
    for w in warnings:
        print("Warning:", w)
    print("Wrote reports/assurance_report.md and reports/policy_brief.md")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
